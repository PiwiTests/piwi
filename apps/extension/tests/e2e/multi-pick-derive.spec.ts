const MAPS = { tagRoles: TAG_TO_ROLE, inputRoles: INPUT_TYPE_TO_ROLE };

/** Installs `repeatedContainers` and the imports `derivePattern` and it reach as globals, from their source text. */
async function installGlobals(page: Page): Promise<void> {
  await page.evaluate(
    ([roleSrc, autoGenSrc, stabilitySrc, quoteSrc, containersSrc]) => {
      (globalThis as any).domRoleOf = new Function(`return (${roleSrc})`)();
      (globalThis as any).isAutoGenerated = new Function(`return (${autoGenSrc})`)();
      (globalThis as any).classifyCssStability = new Function(`return (${stabilitySrc})`)();
      (globalThis as any).quoteJsString = new Function(`return (${quoteSrc})`)();
      (globalThis as any).repeatedContainers = new Function(`return (${containersSrc})`)();
    },
    [
      domRoleOf.toString(),
      isAutoGenerated.toString(),
      classifyCssStability.toString(),
      quoteJsString.toString(),
      repeatedContainers.toString(),
    ],
  );
}

/**
 * `derivePattern` nests every helper inside its own body (see that function's
 * doc comment): only its genuine cross-module imports — `domRoleOf`, `isAutoGenerated`,
 * `classifyCssStability`, `quoteJsString`, `repeatedContainers` — need installing as globals first. The page it
 * reads is every element, open shadow roots included, and an element counts as
 * hidden when the browser does not render it or it sits under `aria-hidden`; with `names`, an element is named by
 * its `aria-label` or its text, which is enough for these fixtures;
 * `multi-pick.spec.ts` checks the bundle's own wiring through the page engine.
 * `selector` picks in the document, or in the shadow root of `host`.
 */
async function evalDerive(
  page: Page,
  selector: string,
  count: number,
  host?: string,
  names = false,
): Promise<{ baseLocator: string | null; count: number; rows: { locator: string; indexBased: boolean }[] }> {
  await installGlobals(page);
  return page.evaluate(
    ([fnSrc, sel, n, maps, hostSel, named]) => {
      const derive = new Function(`return (${fnSrc})`)() as typeof derivePattern;
      const elements: Element[] = [];
      const visit = (root: Document | ShadowRoot) => {
        for (const el of root.querySelectorAll('*')) elements.push(el);
        for (const el of root.querySelectorAll('*')) if (el.shadowRoot) visit(el.shadowRoot);
      };
      visit(document);
      const isHidden = (el: Element) =>
        !el.checkVisibility({ visibilityProperty: true }) || !!el.closest('[aria-hidden="true"]');
      const scope = hostSel ? document.querySelector(hostSel)!.shadowRoot! : document;
      const picked = [...scope.querySelectorAll(sel)].slice(0, n);
      const nameOf = (el: Element) =>
        (el.getAttribute('aria-label') || el.textContent || '').replace(/\s+/g, ' ').trim();
      const result = derive(picked, maps as typeof MAPS, { elements, isHidden, ...(named ? { nameOf } : {}) });
      return {
        baseLocator: result.baseLocator,
        count: result.count,
        rows: result.rows.map((r) => ({ locator: r.locator, indexBased: r.indexBased })),
      };
    },
    [derivePattern.toString(), selector, count, MAPS, host, names] as const,
  );
}

/** The pattern's base finds `count` elements with real Playwright, and each row finds its pick alone. */
async function expectFound(
  page: Page,
  result: { baseLocator: string | null; count: number; rows: { locator: string }[] },
  picks: string[],
): Promise<void> {
  await expect(playwrightLocator(page, result.baseLocator!)).toHaveCount(result.count);
  for (const [i, row] of result.rows.entries()) {
    await expect(playwrightLocator(page, row.locator)).toHaveCount(1);
    await expect(playwrightLocator(page, row.locator)).toHaveAttribute('id', picks[i]!);
  }
}

test.describe('derivePattern', () => {
  test('derives a getByRole(row) pattern with per-row hasText discriminators', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <table><tbody>
        <tr><td>Alice - active</td></tr>
        <tr><td>Bob - active</td></tr>
        <tr><td>Carol - suspended</td></tr>
      </tbody></table>
    </body></html>`);

    const result = await evalDerive(page, 'tr', 2);
    expect(result.baseLocator).toBe(`getByRole('row')`);
    expect(result.rows).toEqual([
      { locator: `getByRole('row').filter({ hasText: 'Alice' })`, indexBased: false },
      { locator: `getByRole('row').filter({ hasText: 'Bob' })`, indexBased: false },
    ]);
  });

  test('falls back to nth() with indexBased: true when rows share identical text', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <table><tbody>
        <tr><td>Loading…</td></tr>
        <tr><td>Loading…</td></tr>
      </tbody></table>
    </body></html>`);

    const result = await evalDerive(page, 'tr', 2);
    expect(result.rows).toEqual([
      { locator: `getByRole('row').nth(0)`, indexBased: true },
      { locator: `getByRole('row').nth(1)`, indexBased: true },
    ]);
  });

  test('falls back to a shared stable CSS class when elements share no role (cards), preferring the more distinctive of several shared classes', async ({
    context,
  }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <div class="card product-card">Widget A</div>
      <div class="card product-card">Widget B</div>
    </body></html>`);

    // Both "card" and "product-card" are shared, but "product-card" scores
    // higher under classifyCssStability (multi-word kebab-case vs. a single
    // short generic word), so it should win.
    const result = await evalDerive(page, '.card', 2);
    expect(result.baseLocator).toBe(`locator('.product-card')`);
    expect(result.rows).toHaveLength(2);
    expect(result.rows.every((r) => !r.indexBased)).toBe(true);
  });

  test('prefers a more stable shared class over a hashed/auto-generated one', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <div class="css-a1b2c3d4 product-card">Widget A</div>
      <div class="css-a1b2c3d4 product-card">Widget B</div>
    </body></html>`);

    const result = await evalDerive(page, '.product-card', 2);
    expect(result.baseLocator).toBe(`locator('.product-card')`);
  });

  test('counts nth() among the rows getByRole finds, a hidden one aside', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body><ul>
      <li style="display:none">Loading…</li>
      <li id="first">Loading…</li>
      <li id="second">Loading…</li>
    </ul></body></html>`);
    const result = await evalDerive(page, 'li:not([style])', 2);
    expect(result.rows.map((r) => r.locator)).toEqual([`getByRole('listitem').nth(0)`, `getByRole('listitem').nth(1)`]);
    await expect(playwrightLocator(page, result.rows[0]!.locator)).toHaveAttribute('id', 'first');
    await expect(playwrightLocator(page, result.rows[1]!.locator)).toHaveAttribute('id', 'second');
  });

  test('counts the rows inside a web component, after the page’s own', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <ul><li>Loading…</li></ul>
      <todo-list></todo-list>
      <script>
        customElements.define('todo-list', class extends HTMLElement {
          constructor() {
            super();
            this.attachShadow({ mode: 'open' }).innerHTML =
              '<ul><li id="first">Loading…</li><li id="second">Loading…</li></ul>';
          }
        });
      </script>
    </body></html>`);
    const result = await evalDerive(page, 'li', 2, 'todo-list');
    expect(result.rows.map((r) => r.locator)).toEqual([`getByRole('listitem').nth(1)`, `getByRole('listitem').nth(2)`]);
    await expect(playwrightLocator(page, result.rows[0]!.locator)).toHaveAttribute('id', 'first');
    await expect(playwrightLocator(page, result.rows[1]!.locator)).toHaveAttribute('id', 'second');
  });

  test('escapes a class that is not a plain CSS identifier', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <div class="md:flex">Widget A</div>
      <div class="md:flex">Widget B</div>
    </body></html>`);
    const result = await evalDerive(page, 'div', 2);
    expect(result.baseLocator).toBe(`locator('.md\\\\:flex')`);
    await expect(playwrightLocator(page, result.baseLocator!)).toHaveCount(2);
    await expect(playwrightLocator(page, result.rows[1]!.locator)).toHaveText('Widget B');
  });

  test('derives the rows the picked buttons repeat in, each row filtered by a cell of its own', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <table>
        <thead><tr><th>Name</th><th>Role</th><th>Actions</th></tr></thead>
        <tbody>
          <tr><td>Alice</td><td>Admin</td><td><button id="a">Delete</button></td></tr>
          <tr><td>Bob</td><td>Editor</td><td><button id="b">Delete</button></td></tr>
          <tr><td>Carol</td><td>Editor</td><td><button id="c">Delete</button></td></tr>
        </tbody>
      </table>
    </body></html>`);
    const result = await evalDerive(page, 'button', 2, undefined, true);
    expect(result).toEqual({
      baseLocator: `getByRole('row').getByRole('button', { name: 'Delete' })`,
      count: 3,
      rows: [
        {
          locator: `getByRole('row').filter({ hasText: 'Alice' }).getByRole('button', { name: 'Delete' })`,
          indexBased: false,
        },
        {
          locator: `getByRole('row').filter({ hasText: 'Bob' }).getByRole('button', { name: 'Delete' })`,
          indexBased: false,
        },
      ],
    });
    await expectFound(page, result, ['a', 'b']);
  });

  test('derives the cards the picked buttons repeat in, by their shared test id and their headings', async ({
    context,
  }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body><main>
      <article data-testid="product-card"><h3>Blue mug</h3><p>12 €</p>
        <button id="blue">Add to cart</button><button aria-label="Add Blue mug to wishlist">♡</button></article>
      <article data-testid="product-card"><h3>Red mug</h3><p>14 €</p>
        <button id="red">Add to cart</button><button aria-label="Add Red mug to wishlist">♡</button></article>
      <article data-testid="product-card"><h3>Green mug</h3><p>16 €</p>
        <button id="green">Add to cart</button><button aria-label="Add Green mug to wishlist">♡</button></article>
      <article data-testid="product-card"><h3>Travel mug</h3><p>22 €</p>
        <button id="travel">Add to cart</button><button aria-label="Add Travel mug to wishlist">♡</button></article>
    </main></body></html>`);
    const result = await evalDerive(page, '#blue, #green', 2, undefined, true);
    expect(result).toEqual({
      baseLocator: `getByTestId('product-card').getByRole('button', { name: 'Add to cart' })`,
      count: 4,
      rows: [
        {
          locator: `getByTestId('product-card').filter({ hasText: 'Blue mug' }).getByRole('button', { name: 'Add to cart' })`,
          indexBased: false,
        },
        {
          locator: `getByTestId('product-card').filter({ hasText: 'Green mug' }).getByRole('button', { name: 'Add to cart' })`,
          indexBased: false,
        },
      ],
    });
    await expectFound(page, result, ['blue', 'green']);
  });

  test('counts the picks by position among the containers when no text tells the containers apart', async ({
    context,
  }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body><ul>
      <li>Untitled draft <button id="first">Open</button></li>
      <li>Untitled draft <button id="second">Open</button></li>
      <li>Untitled draft <button id="third">Open</button></li>
    </ul></body></html>`);
    const result = await evalDerive(page, '#second, #third', 2, undefined, true);
    expect(result).toEqual({
      baseLocator: `getByRole('listitem').getByRole('button', { name: 'Open' })`,
      count: 3,
      rows: [
        { locator: `getByRole('listitem').getByRole('button', { name: 'Open' }).nth(1)`, indexBased: true },
        { locator: `getByRole('listitem').getByRole('button', { name: 'Open' }).nth(2)`, indexBased: true },
      ],
    });
    await expectFound(page, result, ['second', 'third']);
  });

  test('keeps the picks’ own pattern when each container holds more than the pick', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <div class="tile"><button>Keep</button><button>Archive</button></div>
      <div class="tile"><button>Keep</button><button>Archive</button></div>
    </body></html>`);
    // The picks' names differ, so inside a tile the bare role finds both buttons: no container pattern.
    const result = await evalDerive(page, '.tile:first-child button', 2, undefined, true);
    expect(result.baseLocator).toBe(`getByRole('button')`);
    expect(result.count).toBe(4);
  });

  test('finds no pattern when picks share neither a role nor a class', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body>
      <button>Save</button>
      <img alt="logo" src="x.png" />
    </body></html>`);

    const result = await evalDerive(page, 'button, img', 2);
    expect(result).toEqual({ baseLocator: null, count: 0, rows: [] });
  });

  test('fewer than 2 picked elements yields no pattern', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body><button>Save</button></body></html>`);
    const result = await evalDerive(page, 'button', 1);
    expect(result).toEqual({ baseLocator: null, count: 0, rows: [] });
  });
});

test.describe('repeatedContainers', () => {
  test('reads each row of a 1,000-row table once to tell one row apart, however many texts it tries', async ({
    context,
  }) => {
    const page = await context.newPage();
    // Twenty texts a row, every one but the name shared with the other rows.
    const shared = ['Active', 'Admin', 'France', 'Paris', 'EUR', 'Premium', 'Yes', 'No', 'Monthly', 'Card'];
    const rows = Array.from({ length: 1000 }, (_, i) => {
      const cells = [`Customer ${i + 1000}`, ...shared, ...shared.map((s) => `${s} plan`).slice(0, 9)];
      return `<tr>${cells.map((c) => `<td>${c}</td>`).join('')}<td><button>Delete</button></td></tr>`;
    });
    await page.setContent(`<!doctype html><html><body><table><tbody>${rows.join('')}</tbody></table></body></html>`);
    await installGlobals(page);
    const { texts, reads, ms } = await page.evaluate(() => {
      const find = (globalThis as any).repeatedContainers as typeof repeatedContainers;
      let reads = 0;
      const textOf = (el: Element) => {
        reads++;
        return (el.textContent || '').replace(/\s+/g, ' ').trim();
      };
      const roleOf = (el: Element) => (el.tagName === 'TR' ? 'row' : el.tagName === 'TD' ? 'cell' : null);
      const started = performance.now();
      const texts: string[][] = [];
      for (const button of [...document.querySelectorAll('button')].slice(0, 200)) {
        const containers = find(button, { roleOf, testIdAttributes: ['data-testid'], textOf });
        const row = containers.find((c) => c.role === 'row')!;
        texts.push(row.textsAmong(row.siblings));
      }
      return { texts, reads, ms: performance.now() - started };
    });
    console.log(`textsAmong for 200 rows of a 1,000-row table: ${ms.toFixed(0)} ms, ${reads} texts read`);
    expect(texts[0]).toEqual(['Customer 1000']);
    expect(texts[199]).toEqual(['Customer 1199']);
    // Each call reads every row's text at most once, not once per text it tries.
    expect(reads).toBeLessThanOrEqual(200 * 1000);
  });

  test('reads the texts through lowerTextOf when given, not textOf', async ({ context }) => {
    const page = await context.newPage();
    await page.setContent(`<!doctype html><html><body><ul>
      <li>Alice <button>Delete</button></li><li>Bob <button>Delete</button></li>
    </ul></body></html>`);
    await installGlobals(page);
    const result = await page.evaluate(() => {
      const find = (globalThis as any).repeatedContainers as typeof repeatedContainers;
      const lowered: string[] = [];
      const [item] = find(document.querySelector('button')!, {
        roleOf: (el) => (el.tagName === 'LI' ? 'listitem' : null),
        testIdAttributes: ['data-testid'],
        textOf: () => {
          throw new Error('lowerTextOf reads the texts');
        },
        lowerTextOf: (el) => {
          const text = el.textContent!.replace(/\s+/g, ' ').trim();
          lowered.push(text);
          return text.toLowerCase();
        },
      });
      return { texts: item!.textsAmong(item!.siblings), lowered };
    });
    expect(result).toEqual({ texts: ['Alice'], lowered: ['Alice Delete', 'Bob Delete'] });
  });
});
