import { isAutoGenerated, classifyCssStability } from '@piwitests/core/locator-generation';
import { quoteJsString } from '@piwitests/core/locator-chain';

/** An ancestor that repeats beside siblings of its own kind: a table row, a list item, a card. */
export interface RepeatedContainer {
  element: Element;
  /**
   * The locator finding every container of this kind: `getByTestId('product-card')` when the siblings share a test
   * id, `getByRole('row')` when they share a tag and a role, `locator('.card')` when they share a tag and a class.
   */
  base: string;
  /** The role `base` finds the containers by, null for a test id or a class. */
  role: string | null;
  /** Whether `other` is a container of the same kind, as `base` finds it (visibility aside). */
  matches: (other: Element) => boolean;
  /** The container and its siblings of the same kind, in document order. */
  siblings: Element[];
  /**
   * Short texts inside the container, outside the element the containers were found for, that no other element
   * of `pool` contains (as `filter({ hasText })` matches, case aside): a heading first, then a text that names
   * rather than counts, the shorter first. At most three.
   */
  textsAmong: (pool: readonly Element[]) => string[];
}

export interface ContainerOptions {
  /** The role Playwright gives an element, null when it has none. */
  roleOf: (el: Element) => string | null;
  /** The attributes `getByTestId` reads, the first one set on a container naming it. */
  testIdAttributes: readonly string[];
  /** The text `filter({ hasText })` matches an element by; its whitespace-collapsed `textContent` otherwise. */
  textOf?: (el: Element) => string;
  /** How many ancestors to look through. */
  maxDepth?: number;
}

/**
 * The ancestors of `el` that repeat, nearest first: each has a sibling of the same kind (the same test id, or the
 * same tag with the same role or a shared readable class), which is how a list, a grid of cards or a table body is
 * built. A test filters such a container by a text it shows and searches inside it, as Playwright's guide does for
 * lists: `getByRole('row').filter({ hasText: 'Alice' }).getByRole('button', { name: 'Delete' })`.
 *
 * Every helper is nested here: `multi-pick-derive.spec.ts` runs this function from its source text
 * (`Function.prototype.toString()`), with `isAutoGenerated`, `classifyCssStability` and `quoteJsString` installed
 * as globals.
 */
export function repeatedContainers(el: Element, options: ContainerOptions): RepeatedContainer[] {
  const { roleOf, testIdAttributes, maxDepth = 15 } = options;
  const normalize = (s: string): string => s.replace(/\s+/g, ' ').trim();
  const textOf = options.textOf ?? ((node: Element) => normalize(node.textContent || ''));
  const ROLELESS = ['generic', 'none', 'presentation'];
  /** A container of more elements than this is left without texts, which keeps the search short on a large page. */
  const MAX_CONTAINER_ELEMENTS = 200;
  const MAX_TEXT_LENGTH = 60;

  const readableClass = (cls: string): boolean => {
    if (isAutoGenerated(cls) || /^(?:css|sc|emotion|styled)-/i.test(cls)) return false;
    const score = classifyCssStability(cls);
    // 10 is a hash, 25 a utility class; 15 is kept for a plain word only (`card`, `item`).
    return score >= 35 || (score === 15 && /^[a-z][a-z0-9]*$/i.test(cls));
  };

  const parentOf = (node: Element): Element | null =>
    node.parentElement ?? ((node.parentNode as ShadowRoot | null)?.host || null);

  const textsAmong = (container: Element) => {
    const found = new Map<readonly Element[], string[]>();
    return (pool: readonly Element[]): string[] => {
      const cached = found.get(pool);
      if (cached) return cached;
      const result: string[] = [];
      found.set(pool, result);
      if (container.querySelectorAll('*').length > MAX_CONTAINER_ELEMENTS) return result;
      const candidates: Array<{ text: string; rank: number; order: number }> = [];
      const seen = new Set<string>();
      const add = (raw: string, heading: boolean) => {
        const text = normalize(raw);
        if (!text || text.length > MAX_TEXT_LENGTH || seen.has(text) || !/[\p{L}\p{N}]/u.test(text)) return;
        seen.add(text);
        const digits = text.replace(/[^0-9]/g, '').length;
        const letters = text.replace(/[^\p{L}]/gu, '').length;
        const rank = heading ? 0 : digits <= letters ? 1 : 2;
        candidates.push({ text, rank, order: candidates.length });
      };
      for (const heading of container.querySelectorAll('h1,h2,h3,h4,h5,h6,[role="heading"]')) {
        if (heading === el || heading.contains(el) || el.contains(heading)) continue;
        add(heading.textContent || '', true);
      }
      const walker = (container.ownerDocument || document).createTreeWalker(container, NodeFilter.SHOW_TEXT);
      for (let node = walker.nextNode(); node; node = walker.nextNode()) {
        const parent = node.parentElement;
        if (!parent || el.contains(node) || parent.closest('script,style,template,noscript')) continue;
        add(node.nodeValue || '', false);
      }
      candidates.sort((a, b) => a.rank - b.rank || a.text.length - b.text.length || a.order - b.order);
      for (const { text } of candidates) {
        const needle = text.toLowerCase();
        const holders = pool.filter((other) => textOf(other).toLowerCase().includes(needle));
        if (holders.length !== 1 || holders[0] !== container) continue;
        result.push(text);
        if (result.length === 3) break;
      }
      return result;
    };
  };

  const kindOf = (
    node: Element,
    peers: Element[],
  ): (Pick<RepeatedContainer, 'base' | 'role' | 'matches'> & { siblings: Element[] }) | null => {
    for (const attribute of testIdAttributes) {
      const value = node.getAttribute(attribute);
      if (!value) continue;
      const siblings = peers.filter((peer) => peer.getAttribute(attribute) === value);
      if (siblings.length > 1) {
        return {
          base: `getByTestId(${quoteJsString(value)})`,
          role: null,
          matches: (other) => other.getAttribute(attribute) === value,
          siblings,
        };
      }
    }
    const role = roleOf(node);
    if (role && !ROLELESS.includes(role)) {
      const siblings = peers.filter((peer) => peer.tagName === node.tagName && roleOf(peer) === role);
      if (siblings.length > 1) {
        return {
          base: `getByRole(${quoteJsString(role)})`,
          role,
          matches: (other) => roleOf(other) === role,
          siblings,
        };
      }
    }
    let best: { cls: string; score: number; siblings: Element[] } | null = null;
    for (const cls of Array.from(node.classList)) {
      if (!readableClass(cls)) continue;
      const siblings = peers.filter((peer) => peer.tagName === node.tagName && peer.classList.contains(cls));
      const score = classifyCssStability(cls);
      if (siblings.length > 1 && (!best || score > best.score)) best = { cls, score, siblings };
    }
    if (best) {
      const { cls, siblings } = best;
      return {
        base: `locator(${quoteJsString(`.${CSS.escape(cls)}`)})`,
        role: null,
        matches: (other) => other.classList.contains(cls),
        siblings,
      };
    }
    return null;
  };

  const containers: RepeatedContainer[] = [];
  let node = parentOf(el);
  for (let depth = 0; node && depth < maxDepth; depth++, node = parentOf(node)) {
    const tag = node.tagName.toLowerCase();
    if (tag === 'body' || tag === 'html') break;
    const parent = node.parentNode as ParentNode | null;
    const peers = parent ? Array.from(parent.children) : [];
    if (peers.length < 2) continue;
    const kind = kindOf(node, peers);
    if (kind) containers.push({ element: node, ...kind, textsAmong: textsAmong(node) });
  }
  return containers;
}
