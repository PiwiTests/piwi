import { domRoleOf, type DomRoleMaps } from '@piwitests/picker-dom';
import { isAutoGenerated, classifyCssStability } from '@piwitests/core/locator-generation';
import { quoteJsString } from '@piwitests/core/locator-chain';
import { repeatedContainers, type RepeatedContainer } from './repeated-container.js';

interface PatternRow {
  element: Element;
  /** The full locator for this one element, e.g. `getByRole('row').filter({ hasText: 'Alice' })` or `getByRole('row').nth(2)`. */
  locator: string;
  /** True when this row could only be discriminated by position — Playwright will treat it as brittle to reordering. */
  indexBased: boolean;
}

/** The page as the derivation reads it: its elements and which ones `getByRole` skips. */
export interface PatternPage {
  /** Every element of the page, open shadow roots included, in the order Playwright returns them. */
  elements: readonly Element[];
  /** Hidden from the accessibility tree: `getByRole` skips it, so `.nth()` does not count it. */
  isHidden: (el: Element) => boolean;
  /** The role Playwright gives an element; `domRoleOf` with the role maps otherwise. */
  roleOf?: (el: Element) => string | null;
  /** The accessible name Playwright computes for an element; without it, a pattern names no element. */
  nameOf?: (el: Element) => string;
  /** The text `filter({ hasText })` matches an element by; its whitespace-collapsed `textContent` otherwise. */
  textOf?: (el: Element) => string;
  /** The attributes `getByTestId` reads; `data-testid` otherwise. */
  testIdAttributes?: readonly string[];
}

export interface PatternResult {
  /**
   * The shared base all rows narrow from, e.g. `getByRole('row')`, `locator('.card')`, or the picks inside the
   * container they repeat in, `getByTestId('product-card').getByRole('button', { name: 'Add to cart' })`; null when
   * the picks share no pattern.
   */
  baseLocator: string | null;
  /** How many elements `baseLocator` finds on the page. */
  count: number;
  rows: PatternRow[];
}

/**
 * Derive a repeating-list locator pattern from 2-3 similar picked elements.
 *
 * Picks sharing a role that each sit alone in a container of the same repeated
 * kind (a table row, a card: `repeatedContainers`), the containers siblings of
 * one another, get the container's pattern:
 * the base is the container's locator with the picks' role and shared name
 * inside, and each pick is its container filtered by a short text it shows and
 * the other containers do not,
 * `getByTestId('product-card').filter({ hasText: 'Blue mug' }).getByRole('button', { name: 'Add to cart' })`,
 * or the base with `.nth(index)` when no text tells them apart.
 *
 * Otherwise the picks themselves make the pattern:
 * a shared base locator, then per element either `.filter({ hasText })`
 * using the shortest prefix of its own text that's unique among every
 * element sharing that base right now, or — when no prefix of its text is
 * unique (identical/empty rows) — `.nth(index)`, flagged `indexBased` so the
 * UI can show the "breaks on reorder" warning. The elements sharing the base
 * are the ones Playwright finds, in its order: for a role, those not hidden
 * from the accessibility tree; for a class, every element carrying it.
 *
 * Every helper is nested here rather than a module-level sibling: this gets
 * re-serialized via `Function.prototype.toString()` in tests (installing
 * `domRoleOf`/`isAutoGenerated`/`classifyCssStability`/`quoteJsString`/`repeatedContainers` as globals first),
 * which only ever carries a function's own source text.
 */
export function derivePattern(picked: Element[], maps: DomRoleMaps, page: PatternPage): PatternResult {
  function normalize(s: string): string {
    return s.replace(/\s+/g, ' ').trim();
  }

  function shortestUniqueHasText(el: Element, pool: Element[]): string | null {
    const words = normalize(el.textContent || '')
      .split(' ')
      .filter(Boolean);
    for (let n = 1; n <= words.length; n++) {
      const candidate = words.slice(0, n).join(' ');
      const needle = candidate.toLowerCase();
      const matches = pool.filter((other) =>
        normalize(other.textContent || '')
          .toLowerCase()
          .includes(needle),
      );
      if (matches.length === 1) return candidate;
    }
    return null;
  }

  function sharedStableClass(elements: Element[]): string | null {
    const classSets = elements.map((el) => new Set((el.getAttribute('class') || '').split(/\s+/).filter(Boolean)));
    const [first, ...rest] = classSets;
    if (!first) return null;
    const shared = [...first].filter((cls) => !isAutoGenerated(cls) && rest.every((s) => s.has(cls)));
    if (shared.length === 0) return null;
    shared.sort((a, b) => classifyCssStability(b) - classifyCssStability(a));
    return shared[0]!;
  }

  function containerPattern(): PatternResult | null {
    const leafRole = roleOf(picked[0]!);
    if (!leafRole || ['generic', 'none', 'presentation'].includes(leafRole)) return null;
    if (!picked.every((el) => roleOf(el) === leafRole)) return null;
    const names = page.nameOf ? picked.map((el) => normalize(page.nameOf!(el))) : [];
    const name = names[0] && names.every((n) => n === names[0]) ? names[0] : null;
    const leaf = name
      ? `getByRole(${quoteJsString(leafRole)}, { name: ${quoteJsString(name)} })`
      : `getByRole(${quoteJsString(leafRole)})`;
    // As `getByRole` matches a name: whitespace collapsed, any case, a substring.
    const isLeaf = (el: Element): boolean =>
      roleOf(el) === leafRole &&
      !page.isHidden(el) &&
      (!name || normalize(page.nameOf!(el)).toLowerCase().includes(name.toLowerCase()));
    const options = {
      roleOf,
      testIdAttributes: page.testIdAttributes ?? ['data-testid'],
      textOf: page.textOf,
    };
    const perPick = picked.map((el) => repeatedContainers(el, options));
    for (const nearest of perPick[0]!) {
      if (!nearest.base) continue;
      const containers = perPick.map((list) => list.find((c) => c.base === nearest.base));
      if (containers.some((c) => !c)) continue;
      const chosen = containers as RepeatedContainer[];
      // The picks repeat in one list: their containers are distinct siblings, rows of one table, cards of one grid.
      if (new Set(chosen.map((c) => c.element)).size !== chosen.length) continue;
      if (!chosen.every((c) => nearest.siblings.includes(c.element))) continue;
      const alone = chosen.every((c, i) => {
        const inside = page.elements.filter((el) => el !== c.element && c.element.contains(el) && isLeaf(el));
        return inside.length === 1 && inside[0] === picked[i];
      });
      if (!alone) continue;
      const pool = page.elements.filter((el) => nearest.matches(el) && !(nearest.role && page.isHidden(el)));
      const leaves = page.elements.filter((el) => isLeaf(el) && pool.some((c) => c !== el && c.contains(el)));
      const baseLocator = `${nearest.base}.${leaf}`;
      const rows = picked.map((element, i): PatternRow => {
        const [hasText] = chosen[i]!.textsAmong(pool);
        if (hasText != null) {
          return {
            element,
            locator: `${nearest.base}.filter({ hasText: ${quoteJsString(hasText)} }).${leaf}`,
            indexBased: false,
          };
        }
        const index = leaves.indexOf(element);
        return { element, locator: index >= 0 ? `${baseLocator}.nth(${index})` : baseLocator, indexBased: true };
      });
      return { baseLocator, count: leaves.length, rows };
    }
    return null;
  }

  function rowsFor(baseLocator: string, pool: Element[]): PatternRow[] {
    return picked.map((element) => {
      const hasText = shortestUniqueHasText(element, pool);
      if (hasText != null) {
        return { element, locator: `${baseLocator}.filter({ hasText: ${quoteJsString(hasText)} })`, indexBased: false };
      }
      const index = pool.indexOf(element);
      return { element, locator: index >= 0 ? `${baseLocator}.nth(${index})` : baseLocator, indexBased: true };
    });
  }

  const roleOf = page.roleOf ?? ((el: Element) => domRoleOf(el, maps));
  if (picked.length < 2) return { baseLocator: null, count: 0, rows: [] };

  const inContainers = containerPattern();
  if (inContainers) return inContainers;

  const role = roleOf(picked[0]!);
  if (role && picked.every((el) => roleOf(el) === role)) {
    const pool = page.elements.filter((el) => roleOf(el) === role && !page.isHidden(el));
    const baseLocator = `getByRole(${quoteJsString(role)})`;
    return { baseLocator, count: pool.length, rows: rowsFor(baseLocator, pool) };
  }

  const cls = sharedStableClass(picked);
  if (cls != null) {
    const pool = page.elements.filter((el) => el.classList.contains(cls));
    const baseLocator = `locator(${quoteJsString(`.${CSS.escape(cls)}`)})`;
    return { baseLocator, count: pool.length, rows: rowsFor(baseLocator, pool) };
  }

  return { baseLocator: null, count: 0, rows: [] };
}
