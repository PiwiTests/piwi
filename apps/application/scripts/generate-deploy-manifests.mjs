/**
 * Generates the one-click deploy manifests from the same typed env-var registry
 * that produces docs/configuration.md, so a hosting template can never drift
 * from the variables the application actually reads.
 *
 * Unlike docs/configuration.md these files are committed — Render and Fly read
 * them straight from the repository — so drift is caught by a unit test
 * (tests/unit/deploy-manifests.test.ts) that regenerates in memory and compares
 * against what is on disk, rather than by gitignoring the output.
 *
 * Run: npm run app:generate:deploy --workspace=apps/application
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

import { emitCoolifyCompose } from '#shared/deploy/coolify';
import { emitFlyToml } from '#shared/deploy/fly';
import { emitKoyebDeployUrl } from '#shared/deploy/koyeb';
import { emitRailwayTemplate } from '#shared/deploy/railway';
import { emitRenderBlueprint } from '#shared/deploy/render';
import { PIWI_ENV_VARS } from '#shared/piwi-env-vars';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

/**
 * What a one-click deploy provisions. Deliberately short: the app boots with no
 * configuration at all, so anything beyond "don't publish an open dashboard, don't
 * let a stranger create its first administrator and don't store credentials in
 * the clear" belongs in the docs, not in a template.
 */
const DEPLOY_VARS = [
  {
    name: 'PIWI_AUTH_ENABLED',
    value: 'true',
    comment: 'A one-click deploy is reachable from the internet — authentication stays on.',
  },
  { name: 'PIWI_AUTH_SECRET', platformValue: 'generate' },
  { name: 'PIWI_SECRET_KEY', platformValue: 'generate' },
  {
    name: 'PIWI_SETUP_TOKEN',
    platformValue: 'generate',
    comment: 'The first-admin form asks for this value, so only you can create the administrator.',
  },
  { name: 'PIWI_SITE_URL', platformValue: 'url' },
];

const HEADER = [
  'Generated by apps/application/scripts/generate-deploy-manifests.mjs — edit the script, not this file.',
  'Piwi Dashboard — one-click deploy. Docs: https://piwitests.dev/operate/one-click-deploy',
  'Tracks :latest. Pin a version tag before you rely on it — migrations are forward-only.',
];

/** Resolve the declared variables against the registry, so a typo fails here rather than in production. */
function resolveEntries() {
  return DEPLOY_VARS.map((declared) => {
    const meta = PIWI_ENV_VARS[declared.name];
    if (!meta) throw new Error(`${declared.name} is not in apps/application/shared/piwi-env-vars.ts`);
    return {
      name: declared.name,
      value: declared.value ?? '',
      secret: meta.secret === true,
      comment: declared.comment,
      platformValue: declared.platformValue,
    };
  });
}

/**
 * Every generated file, keyed by its path relative to the repository root.
 * Exported so the drift test can compare without touching the filesystem.
 */
export function buildDeployManifests() {
  const entries = resolveEntries();
  const opts = { header: HEADER };

  return {
    'render.yaml': emitRenderBlueprint(entries, opts),
    'fly.toml': emitFlyToml(entries, opts),
    // Railway service settings for a repository-based deploy. The published
    // template carries the image and volume; this covers the rest.
    'railway.json':
      JSON.stringify(
        {
          $schema: 'https://railway.com/railway.schema.json',
          deploy: {
            healthcheckPath: '/api/health',
            healthcheckTimeout: 60,
            numReplicas: 1,
            restartPolicyType: 'ON_FAILURE',
            restartPolicyMaxRetries: 10,
          },
        },
        null,
        2,
      ) + '\n',
    'deploy/railway/template.md': emitRailwayTemplate(entries, opts),
    'deploy/koyeb-deploy-url.txt': emitKoyebDeployUrl(entries, opts),
    'deploy/coolify/docker-compose.yml': emitCoolifyCompose(entries, opts),
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  for (const [relative, contents] of Object.entries(buildDeployManifests())) {
    const target = join(repoRoot, relative);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
    console.log(`✓ ${relative}`);
  }
}
