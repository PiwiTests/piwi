/**
 * The credit the documents Piwi writes outside the dashboard end with (offline
 * exports, quality reports, emails): the small Piwi mark and a link to the
 * project's site. The mark is drawn from `brand-mark.json`, which
 * `scripts/generate-brand-assets.mjs` writes; nothing here loads over the
 * network, so a document stays self-contained.
 */
import { PDFString, rgb, type PDFDocument, type PDFFont, type PDFPage } from 'pdf-lib';
import mark from './brand-mark.json' with { type: 'json' };

/** The mark's view box: x, y, width, height. */
const VIEW = mark.viewBox as [number, number, number, number];

/** The project's site, where every credit links. */
export const BRAND_SITE_URL = 'https://piwitests.dev';
/** The site as printed, so a credit on paper still says where to look. */
export const BRAND_SITE_LABEL = 'piwitests.dev';

/** The brand violet: the mark, and the buttons of an email. */
export const BRAND_VIOLET = mark.color;

/** The content id an email attaches the mark under (`<img src="cid:…">`). */
export const BRAND_MARK_CID = 'piwi-mark';

/** The mark as a PNG data address, for an email preview in the browser where no attachment exists. */
export const BRAND_MARK_DATA_URL = `data:image/png;base64,${mark.png}`;

/** The mark as PNG bytes, for the email attachment. */
export function piwiMarkPng(): Uint8Array {
  const binary = atob(mark.png);
  return Uint8Array.from(binary, (c) => c.charCodeAt(0));
}

/** The mark as inline SVG markup, `size` px tall, in `color` (the brand violet by default). */
export function piwiMarkSvg(size: number, color: string = mark.color): string {
  const [x, y, w, h] = VIEW;
  const width = Math.round((size * w) / h);
  const dots = mark.dots.map((d) => `<circle cx="${d.cx}" cy="${d.cy}" r="${d.r}"/>`).join('');
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${size}" viewBox="${x} ${y} ${w} ${h}" aria-hidden="true" style="display:inline-block;width:${width}px;height:${size}px;vertical-align:-0.15em">` +
    `<g fill="${color}" stroke="${color}" stroke-linejoin="round">` +
    `<path d="${mark.outline} ${mark.lens} ${mark.eye}" fill-rule="evenodd" stroke="none"/>` +
    `<path d="${mark.check.d}" stroke-width="${mark.check.strokeWidth}"/>` +
    `<path d="${mark.perch.d}" fill="none" stroke-width="${mark.perch.strokeWidth}"/>` +
    `${dots}</g></svg>`
  );
}

/** The HTML credit: the mark, `label` (*Generated by Piwi*) and the site, linked; `color` is the text's. */
export function piwiCreditHtml(label: string, color: string): string {
  return (
    `<a href="${BRAND_SITE_URL}" style="color:${color};text-decoration:none;white-space:nowrap">` +
    `${piwiMarkSvg(14)} ${label} · ${BRAND_SITE_LABEL}</a>`
  );
}

/** The Markdown credit: `label` with Piwi linked to the site. */
export function piwiCreditMarkdown(label: string): string {
  return label.replace(/Piwi$/, `[Piwi](${BRAND_SITE_URL})`);
}

function hexColor(hex: string) {
  const v = hex.replace('#', '');
  return rgb(parseInt(v.slice(0, 2), 16) / 255, parseInt(v.slice(2, 4), 16) / 255, parseInt(v.slice(4, 6), 16) / 255);
}

/**
 * Draws the PDF credit on `page`: the mark `size` points tall with its top at
 * (`x`, `top`), then `label · piwitests.dev` in `font`, the whole line a link
 * to the site. The page is white under the mark, so the lens and the eye are
 * drawn white over the outline.
 */
export function drawPiwiCredit(
  doc: PDFDocument,
  page: PDFPage,
  opts: {
    x: number;
    top: number;
    size: number;
    label: string;
    font: PDFFont;
    textSize: number;
    textColor: ReturnType<typeof rgb>;
  },
): void {
  const [vx, vy, vw, vh] = VIEW;
  const scale = opts.size / vh;
  const violet = hexColor(mark.color);
  const white = rgb(1, 1, 1);
  // drawSvgPath takes SVG coordinates (y down) from the origin it is given.
  const at = { x: opts.x - vx * scale, y: opts.top + vy * scale, scale };
  page.drawSvgPath(mark.outline, { ...at, color: violet });
  page.drawSvgPath(mark.lens, { ...at, color: white });
  page.drawSvgPath(mark.eye, { ...at, color: white });
  page.drawSvgPath(mark.check.d, {
    ...at,
    color: violet,
    borderColor: violet,
    borderWidth: mark.check.strokeWidth * scale,
  });
  page.drawSvgPath(mark.perch.d, { ...at, borderColor: violet, borderWidth: mark.perch.strokeWidth * scale });
  for (const d of mark.dots) {
    page.drawCircle({ x: at.x + d.cx * scale, y: at.y - d.cy * scale, size: d.r * scale, color: violet });
  }

  const text = `${opts.label} · ${BRAND_SITE_LABEL}`;
  const textX = opts.x + vw * scale + opts.size * 0.35;
  const baseline = opts.top - opts.size + (opts.size - opts.textSize) / 2 + opts.textSize * 0.2;
  page.drawText(text, { x: textX, y: baseline, size: opts.textSize, font: opts.font, color: opts.textColor });

  const right = textX + opts.font.widthOfTextAtSize(text, opts.textSize);
  const link = doc.context.register(
    doc.context.obj({
      Type: 'Annot',
      Subtype: 'Link',
      Rect: [opts.x, opts.top - opts.size, right, opts.top],
      Border: [0, 0, 0],
      A: { Type: 'Action', S: 'URI', URI: PDFString.of(BRAND_SITE_URL) },
    }),
  );
  page.node.addAnnot(link);
}
