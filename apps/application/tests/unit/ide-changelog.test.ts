import { describe, test, expect } from 'vitest';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { extractIdeEntries, renderHtml, renderMarkdown } from '../../../../scripts/ide-changelog.mjs';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
const script = join(repoRoot, 'scripts', 'ide-changelog.mjs');

const commitUrl = (hash: string) =>
  `https://github.com/PiwiTests/platform/commit/${hash}0000000000000000000000000000000`;
const link = (hash: string) => `[${hash}](${commitUrl(hash)})`;
const entry = (scope: string, text: string, ...hashes: string[]) =>
  `* **${scope}:** ${text} (${hashes.map(link).join(', ')})`;

const HEADING_58 = '## [0.58.0](https://github.com/PiwiTests/platform/compare/v0.57.0...v0.58.0) (2026-10-21)';
const HEADING_57 = '## [0.57.0](https://github.com/PiwiTests/platform/compare/v0.56.0...v0.57.0) (2026-10-20)';
const HEADING_41 = '## [0.41.0](https://github.com/PiwiTests/platform/compare/v0.40.0...v0.41.0) (2026-09-28)';

// Two release-please versions and a polished one (dash bullets, `####` topics, a `<details>` tail).
const CHANGELOG = `# Changelog

> Entries are generated by release-please.

${HEADING_58}


### Features

${entry('app', "keep a test's history across renames", '75ffff7')}
${entry('ide', "capture the editor extensions' illustrations in the real editors", 'ef2ef40')}
${entry('ide', "capture the editor extensions' illustrations in the real editors", '1111111')}
${entry('ide', 'read the `@piwi` section & escape <b>tags</b>', '2222222')}


### Bug Fixes

${entry('app', 'let a failed directory upload settle', 'e6ea6ae')}
${entry('ide', 'keep downloaded traces in a private per-user folder', '6f7fb56', '3333333')}

${HEADING_57}


### Bug Fixes

${entry('app', 'nothing for the editors', '4444444')}

${HEADING_41}

This release brings Piwi into VS Code and JetBrains IDEs.

### ✨ Highlights

- **🧑‍💻 Piwi in your editor** — A VS Code extension and a JetBrains plugin.

### Features

#### Piwi in your editor
- **ide:** add the VS Code extension (${link('2b6db46')})
- **extension:** record file choices (${link('f4ae632')})

<details>
<summary>Bug fixes</summary>

### Bug Fixes

- **ide:** escape the status bar's text (${link('5555555')})

</details>

<!-- notes:polished -->
`;

describe('extractIdeEntries', () => {
  const versions = extractIdeEntries(CHANGELOG);

  test('lists every version, latest first, with its heading', () => {
    expect(versions.map((v) => v.version)).toEqual(['0.58.0', '0.57.0', '0.41.0']);
    expect(versions.map((v) => v.heading)).toEqual([HEADING_58, HEADING_57, HEADING_41]);
  });

  test('keeps the ide entries under their section, without the scope prefix', () => {
    const [latest] = versions;
    expect(latest!.sections.map((s) => s.heading)).toEqual(['Features', 'Bug Fixes']);
    expect(latest!.sections[0]!.entries.map((e) => e.text)).toEqual([
      "capture the editor extensions' illustrations in the real editors",
      'read the `@piwi` section & escape <b>tags</b>',
    ]);
    expect(latest!.sections[1]!.entries).toEqual([
      { text: 'keep downloaded traces in a private per-user folder', links: [link('6f7fb56'), link('3333333')] },
    ]);
  });

  test('merges the links of an entry written once per commit', () => {
    expect(versions[0]!.sections[0]!.entries[0]!.links).toEqual([link('ef2ef40'), link('1111111')]);
  });

  test('gives a version without ide entries no section', () => {
    expect(versions[1]!.sections).toEqual([]);
  });

  test('reads dash bullets under a topic heading and inside a details block', () => {
    expect(versions[2]!.sections).toEqual([
      { heading: 'Features', entries: [{ text: 'add the VS Code extension', links: [link('2b6db46')] }] },
      { heading: 'Bug Fixes', entries: [{ text: "escape the status bar's text", links: [link('5555555')] }] },
    ]);
  });
});

describe('renderMarkdown', () => {
  const markdown = renderMarkdown(extractIdeEntries(CHANGELOG));

  test('is a changelog of the versions with ide entries, headings as in the source', () => {
    expect(markdown.startsWith('# Changelog\n\n')).toBe(true);
    expect(markdown).toContain(`\n${HEADING_58}\n\n### Features\n\n* capture`);
    expect(markdown).toContain(`\n${HEADING_41}\n\n### Features\n\n* add the VS Code extension`);
    expect(markdown).not.toContain(HEADING_57);
    expect(markdown.indexOf(HEADING_58)).toBeLessThan(markdown.indexOf(HEADING_41));
  });

  test('writes each entry once, with every commit link and no scope', () => {
    expect(markdown).toContain(
      `* capture the editor extensions' illustrations in the real editors (${link('ef2ef40')}, ${link('1111111')})\n`,
    );
    expect(markdown).not.toMatch(/\*\*\w+:\*\*/);
    expect(markdown).not.toContain('75ffff7');
  });
});

describe('renderHtml', () => {
  const versions = extractIdeEntries(CHANGELOG);

  test('renders the sections as headings and lists, with links, code and escaped text', () => {
    expect(renderHtml(versions[0]!)).toBe(
      [
        '<h3>Features</h3>',
        '<ul>',
        `  <li>capture the editor extensions' illustrations in the real editors (<a href="${commitUrl('ef2ef40')}">ef2ef40</a>, <a href="${commitUrl('1111111')}">1111111</a>)</li>`,
        `  <li>read the <code>@piwi</code> section &amp; escape &lt;b&gt;tags&lt;/b&gt; (<a href="${commitUrl('2222222')}">2222222</a>)</li>`,
        '</ul>',
        '<h3>Bug Fixes</h3>',
        '<ul>',
        `  <li>keep downloaded traces in a private per-user folder (<a href="${commitUrl('6f7fb56')}">6f7fb56</a>, <a href="${commitUrl('3333333')}">3333333</a>)</li>`,
        '</ul>',
        '',
      ].join('\n'),
    );
  });

  test('says so for a version without ide entries', () => {
    expect(renderHtml(versions[1]!)).toBe('<p>No change to the editor extensions in this release.</p>\n');
  });
});

describe('the repository changelog', () => {
  const changelog = readFileSync(join(repoRoot, 'CHANGELOG.md'), 'utf8');
  const versions = extractIdeEntries(changelog);
  const markdown = renderMarkdown(versions);
  const hashesOf = (line: string) => [...line.matchAll(/\[([0-9a-f]{7,40})\]\(/g)].map((m) => m[1]!);

  test('has every ide entry in the Markdown, and no other scope', () => {
    for (const line of changelog.split('\n')) {
      const scoped = /^[*-] \*\*([a-z]+):\*\*/.exec(line);
      if (!scoped) continue;
      for (const hash of hashesOf(line)) {
        if (scoped[1] === 'ide') expect(markdown, line).toContain(`[${hash}](`);
        else expect(markdown, line).not.toContain(`[${hash}](`);
      }
    }
  });

  test('starts at the latest version', () => {
    expect(versions[0]!.version).toBe(/^## \[?(\d+\.\d+\.\d+)/m.exec(changelog)![1]);
  });

  test('is what the script prints', () => {
    const run = (...args: string[]) => execFileSync('node', [script, ...args], { encoding: 'utf8' });
    expect(run('--format', 'md', '--all')).toBe(markdown);
    expect(run('--format', 'html')).toBe(renderHtml(versions[0]!));
    expect(run('--format', 'html', '--version', `v${versions[0]!.version}`)).toBe(renderHtml(versions[0]!));
  });
});
