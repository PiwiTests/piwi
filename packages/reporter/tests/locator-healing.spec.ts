describe('exactAccessibleName', () => {
  const source = (
    tagName: string,
    attributes: Record<string, string | null>,
    textContent: string | null = null,
    labelText: string | null = null,
  ) => ({ tagName, attributes, textContent, labelText });

  it('takes aria-label verbatim', () => {
    expect(exactAccessibleName(source('button', { 'aria-label': 'Close dialog' }, 'X'), 'button')).toBe('Close dialog');
  });

  it('names a content-named role by its text', () => {
    expect(exactAccessibleName(source('button', {}, 'Save order'), 'button')).toBe('Save order');
    expect(exactAccessibleName(source('a', { href: '/x' }, 'Details'), 'link')).toBe('Details');
  });

  it('names a labeled form field by its label', () => {
    expect(exactAccessibleName(source('input', {}, null, 'Email address'), 'textbox')).toBe('Email address');
  });

  it('defers to the browser when aria-labelledby is present', () => {
    expect(exactAccessibleName(source('button', { 'aria-labelledby': 'h1' }, 'Save'), 'button')).toBeNull();
    // Even alongside an aria-label, which it outranks.
    expect(
      exactAccessibleName(source('button', { 'aria-labelledby': 'h1', 'aria-label': 'Save' }, 'Save'), 'button'),
    ).toBeNull();
  });

  it('defers to the browser for roles not named by their content', () => {
    expect(exactAccessibleName(source('div', {}, 'Some text'), 'region')).toBeNull();
    expect(exactAccessibleName(source('img', { alt: 'A cat' }), 'img')).toBeNull();
  });

  it('defers to the browser for an unlabeled field and an empty content-named element', () => {
    expect(exactAccessibleName(source('input', {}), 'textbox')).toBeNull();
    expect(exactAccessibleName(source('button', {}, ''), 'button')).toBeNull();
  });

  it('defers to the browser when the probed string may have been truncated', () => {
    // The probe caps textContent at 80 chars and labelText at 120; a value
    // sitting at the cap may be cut short, and a truncated name would build a
    // getByRole locator that matches nothing.
    expect(exactAccessibleName(source('button', {}, 'a'.repeat(80)), 'button')).toBeNull();
    expect(exactAccessibleName(source('button', {}, 'a'.repeat(79)), 'button')).toBe('a'.repeat(79));
    expect(exactAccessibleName(source('input', {}, null, 'b'.repeat(120)), 'textbox')).toBeNull();
    expect(exactAccessibleName(source('input', {}, null, 'b'.repeat(119)), 'textbox')).toBe('b'.repeat(119));
  });
});
