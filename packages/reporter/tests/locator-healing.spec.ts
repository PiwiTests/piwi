    expect(alts.find((a) => a.locator.includes('[name='))).toBeUndefined();
    expect(alts.find((a) => a.locator.includes('.btn'))).toBeUndefined();
    expect(alts.find((a) => a.locator.includes('.card-title'))).toBeTruthy();
