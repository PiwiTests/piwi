function makeAttrs(overrides: Partial<ElementAttributes & { attrs: Record<string, string | null> }> = {}) {
  const a = overrides.attrs ?? {};
  return {
    tagName: overrides.tagName ?? 'button',
    attributes: {
      id: a.id ?? null,
      class: a.class ?? null,
      name: a.name ?? null,
      'data-testid': a['data-testid'] ?? null,
      placeholder: a.placeholder ?? null,
      alt: a.alt ?? null,
      title: a.title ?? null,
      'aria-label': a['aria-label'] ?? null,
      'aria-level': a['aria-level'] ?? null,
      role: a.role ?? null,
      type: a.type ?? null,
      href: a.href ?? null,
      multiple: a.multiple ?? null,
    },
    textContent: overrides.textContent ?? null,
    accessibleName: overrides.accessibleName ?? null,
    center: overrides.center ?? null,
    ...(overrides.hasLabel !== undefined ? { hasLabel: overrides.hasLabel } : {}),
    ...(overrides.selectorCounts !== undefined ? { selectorCounts: overrides.selectorCounts } : {}),
    ...(overrides.rolePosition !== undefined ? { rolePosition: overrides.rolePosition } : {}),
    ...(overrides.ancestors !== undefined ? { ancestors: overrides.ancestors } : {}),
  };
}

/** An anchor-worthy ancestor with sensible defaults for the structural tests. */
function makeAnchor(overrides: Partial<AncestorAnchor> = {}) {
  return {
    tag: 'form',
    depth: 1,
    testId: null,
    id: null,
    role: null,
    ariaLabel: null,
    scopedRoleCount: 1,
    ...overrides,
  };
}

