/**
 * Locator generation — pure functions for building ranked alternative locators
 * from element attributes. The single source of truth shared by the server, the
 * dashboard SPA, the interactive DOM snapshot picker (which runs in the
 * browser), and the Playwright reporter (which bundles this at build time).
 */
import type {
  RankedLocator,
  ElementAttributes,
  SelectorCounts,
  RolePosition,
  AncestorAnchor,
} from './locator-healing-types';
import { quoteJsString } from './locator-chain';

export type { RankedLocator, ElementAttributes, SelectorCounts, RolePosition, AncestorAnchor };

